//------------------------------------------------------------------------------
// Файл       : de10_lite_top.sv
// Модуль     : de10_lite_top — модуль верхнего уровня для платы Terasic DE10-Lite
// Тактовая   : 50 МГц (вывод PIN_P11)
//
// Назначение выводов платы:
//   * MAX10_CLK1_50 — тактовый генератор 50 МГц
//   * KEY[0]        — кнопка сброса (активный уровень '0')
//   * SW[0]         — переключатель разрешения опроса датчика ('1' — вкл.)
//   * GPIO[0]       — выход Trig на датчик HC-SR04
//   * GPIO[1]       — вход Echo от датчика HC-SR04 (через делитель 5 В -> 3,3 В)
//   * HEX3..HEX0    — вывод измеренного расстояния в миллиметрах
//   * HEX5..HEX4    — погашены
//   * LEDR[0]       — индикация включения опроса (SW[0])
//   * LEDR[1]       — индикация ошибки измерения (err)
//   * LEDR[2]       — монитор сигнала Echo в реальном времени
//------------------------------------------------------------------------------
module de10_lite_top (
  input  logic       MAX10_CLK1_50, // 50 МГц (PIN_P11)
  input  logic [1:0] KEY,           // Кнопки (активный '0')
  input  logic [9:0] SW,            // Переключатели
  inout  wire  [1:0] GPIO,          // GPIO[0] - Trig, GPIO[1] - Echo
  output logic [9:0] LEDR,          // Светодиоды
  output logic [7:0] HEX0,          // Семисегментный индикатор (единицы мм)
  output logic [7:0] HEX1,          // Семисегментный индикатор (десятки мм)
  output logic [7:0] HEX2,          // Семисегментный индикатор (сотни мм)
  output logic [7:0] HEX3,          // Семисегментный индикатор (тысячи мм)
  output logic [7:0] HEX4,          // Семисегментный индикатор (не используется)
  output logic [7:0] HEX5           // Семисегментный индикатор (не используется)
);

  import rangefinder_pkg::*;

  //----------------------------------------------------------------------------
  // Внутренние сигналы и регистры
  //----------------------------------------------------------------------------
  logic                  rst_btn;
  logic                  rst_sync;
  logic [1:0]            rst_chain = 2'b11; // начальный сброс при загрузке ПЛИС

  logic                  trig_sig;
  logic                  echo_sig;
  logic [DIST_WIDTH-1:0] dist_mm;
  logic                  err_sig;
  logic                  strobe;

  //============================================================================
  // 1. Формирование и синхронизация сигнала сброса
  //============================================================================
  // Кнопки на плате DE10-Lite имеют активный низкий уровень ('0' при нажатии)
  assign rst_btn = ~KEY[0];

  // Двухступенчатый синхронизатор сброса для модуля индикации
  always_ff @(posedge MAX10_CLK1_50) begin : p_rst_sync
    rst_chain <= {rst_chain[0], rst_btn};
  end

  assign rst_sync = rst_chain[1];

  //============================================================================
  // 2. Буферы двунаправленного разъёма GPIO
  //============================================================================
  // GPIO[0] работает на выход (Trig), GPIO[1] работает на вход (Echo)
  assign GPIO[0]  = trig_sig;
  assign GPIO[1]  = 1'bz;     // обязательно переводим выходной буфер GPIO[1] в Z-состояние
  assign echo_sig = GPIO[1];

  //============================================================================
  // 3. Модуль 1: Опрос датчика HC-SR04 и фильтрация (50 МГц по умолчанию)
  //============================================================================
  rangefinder_top u_rangefinder (
    .clk     (MAX10_CLK1_50),
    .reset   (rst_btn),
    .sw_en   (SW[0]),
    .echo    (echo_sig),
    .trig    (trig_sig),
    .dist_mm (dist_mm),
    .err     (err_sig),
    .strobe  (strobe)
  );

  //============================================================================
  // 4. Модуль 2: Вывод расстояния на семисегментные индикаторы HEX3..HEX0
  //============================================================================
  // Примечание: в SystemVerilog идентификатор "dist" является зарезервированным
  // ключевым словом, поэтому для обращения к VHDL-порту dist используется
  // экранированное имя .\dist (с обязательным пробелом перед скобкой).
  distance_display u_display (
    .clk    (MAX10_CLK1_50),
    .rst    (rst_sync),
    .\dist  (dist_mm),
    .strobe (strobe),
    .err    (err_sig),
    .HEX0   (HEX0),
    .HEX1   (HEX1),
    .HEX2   (HEX2),
    .HEX3   (HEX3)
  );

  //============================================================================
  // 5. Управление неиспользуемыми индикаторами и светодиодами
  //============================================================================
  // Гасим неиспользуемые индикаторы HEX4 и HEX5 (активный уровень сегментов — '0')
  assign HEX4 = '1;
  assign HEX5 = '1;

  // Индикация на светодиодах
  assign LEDR[0]   = SW[0];     // горит при включённом опросе
  assign LEDR[1]   = err_sig;   // горит при ошибке измерения
  assign LEDR[2]   = echo_sig;  // отображает сигнал Echo
  assign LEDR[9:3] = '0;        // остальные светодиоды погашены

endmodule : de10_lite_top